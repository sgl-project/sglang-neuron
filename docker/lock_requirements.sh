#!/usr/bin/env bash
# docker/lock_requirements.sh: regenerate docker/requirements-lock.txt, docker/qa-requirements-lock.txt,
# docker/torchvision-lock.txt and docker/wheel-build-lock.txt (docker/lock_requirements.py) in the Dockerfile's base
# image, at the Dockerfile's SGLang commit and torchvision version. Needs docker and network access. Review the diff,
# then rebuild and re-test the image.
#
#   docker/lock_requirements.sh                            # keep every locked version; resolve only what changed
#   docker/lock_requirements.sh --upgrade-package <name>   # let one package (repeatable) move to its newest release
#   docker/lock_requirements.sh --upgrade                  # resolve every package again
set -euo pipefail

die() { echo "lock_requirements: $*" >&2; exit 1; }
# not `readonly ROOT=$(...)`, whose status is readonly's: outside a checkout that said "an ARG is missing" instead
ROOT=$(git -C "$(dirname "$0")" rev-parse --show-toplevel) || die "run it from a git checkout of this repository"
readonly ROOT
for arg in "$@"; do  # the script gives these itself; a caller's --out would win and leave nothing to copy
    case ${arg} in --out|--out=*|--repo|--repo=*) die "${arg%%=*} is the script's own option" ;; esac
done
arg() { sed -n "s/^ARG $1=//p" "${ROOT}/docker/Dockerfile"; }
readonly BASE=$(arg BASE) SGLANG_COMMIT=$(arg SGLANG_COMMIT) SGLANG_VERSION=$(arg SGLANG_VERSION) \
    TORCHVISION_VERSION=$(arg TORCHVISION_VERSION) \
    TORCHVISION_INDEX=$(arg TORCHVISION_INDEX)
for value in "${BASE}" "${SGLANG_COMMIT}" "${SGLANG_VERSION}" "${TORCHVISION_VERSION}" "${TORCHVISION_INDEX}"; do
    [[ -n "${value}" ]] || die "an ARG is missing from docker/Dockerfile"
done
readonly OUT=$(mktemp -d)
trap 'rm -rf "${OUT}"' EXIT

docker run --rm -v "${ROOT}:/src:ro" -v "${OUT}:/out" --entrypoint python3 "${BASE}" /src/docker/lock_requirements.py \
    --repo /src --sglang-commit "${SGLANG_COMMIT}" --sglang-version "${SGLANG_VERSION}" \
    --torchvision "${TORCHVISION_VERSION}" \
    --torchvision-index "${TORCHVISION_INDEX}" --out /out "$@"
# every lock written, or none: the repository's locks are replaced only once all four outputs are there, each through
# a temporary file and a rename, so a run that wrote no lock (or lost one) leaves the committed ones as they were
readonly LOCKS=(requirements-lock.txt qa-requirements-lock.txt torchvision-lock.txt wheel-build-lock.txt)
for file in "${LOCKS[@]}"; do
    [[ -s ${OUT}/${file} ]] || die "the lock tool wrote no ${file}; the repository's locks are unchanged"
done
for file in "${LOCKS[@]}"; do
    { echo "# Generated by docker/lock_requirements.sh (base ${BASE##*@}, SGLang ${SGLANG_COMMIT:0:8}); do not edit."
      cat "${OUT}/${file}"; } > "${ROOT}/docker/${file}.tmp"
done
for file in "${LOCKS[@]}"; do
    mv "${ROOT}/docker/${file}.tmp" "${ROOT}/docker/${file}"
    echo "docker/${file}: $(grep -vc '^#' "${ROOT}/docker/${file}") packages"
done
